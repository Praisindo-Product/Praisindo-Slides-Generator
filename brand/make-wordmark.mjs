// Writes the Praisindo wordmark's outlines into brand/praisindo-wordmark.ts, for the lockup in engine/slide.tsx.
//
//   node brand/make-wordmark.mjs        (or: npm run wordmark)
//
// "Praisindo" in Fraunces, an open-licence serif (fonts/OFL-fraunces.txt), kerned and very slightly
// tracked. fonts/fraunces-display.ttf is the variable font fixed at weight 380, optical size 72,
// softness 50 and no wonk. The outlines are in font units, y down, with the baseline at y = 0.
// Run from the repository root after changing the font or the spacing; the output is committed
// so building a deck needs no font tooling.

import * as fontkit from "fontkit";
import { writeFileSync } from "node:fs";
import path from "node:path";

const FONT = "fonts/fraunces-display.ttf";
const TEXT = "Praisindo";
// Added between letters, in em, on top of the font's own spacing and kerning.
const TRACKING = 0.025;

const font = fontkit.openSync(path.resolve(FONT));
const em = font.unitsPerEm;
const round = (value) => Math.round(value * 10) / 10;

const run = font.layout(TEXT);
let x = 0;
let top = 0;
const body = run.glyphs.map((glyph, index) => {
  const left = x + run.positions[index].xOffset;
  top = Math.max(top, glyph.bbox.maxY);
  x += run.positions[index].xAdvance + (index < run.glyphs.length - 1 ? TRACKING * em : 0);
  return glyph.path.mapPoints((px, py) => [round(left + px), round(-py)]).toSVG();
});

const out = path.resolve("brand/praisindo-wordmark.ts");
writeFileSync(
  out,
  [
    "// Generated by brand/make-wordmark.mjs from " + FONT + ". Do not edit by hand.",
    "",
    "export const PRAISINDO_WORDMARK = " + JSON.stringify({ em, capHeight: font.capHeight, top: round(top), width: round(x), body: body.join(" ") }, null, 2) + " as const;",
    "",
  ].join("\n"),
);
console.log("Wrote " + path.relative(process.cwd(), out));
